#!/usr/bin/env bash
set -euo pipefail

theme_dir="${1:-src/cros_theme}"
output="${2:-src/cros_theme_tailwind.css}"

colors="$theme_dir/colors.css"
typography="$theme_dir/typography.css"

if [[ ! -f "$colors" ]]; then
  printf 'error: missing %s\n' "$colors" >&2
  exit 1
fi

if [[ ! -f "$typography" ]]; then
  printf 'error: missing %s\n' "$typography" >&2
  exit 1
fi

mkdir -p "$(dirname "$output")"

{
  printf '%s\n' '/* generated by scripts/generate-cros-theme-tailwind.sh */'
  printf '%s\n' '/* do not edit manually */'
  printf '%s\n\n' '@theme {'

  awk '
    /^[[:space:]]*--cros_[A-Za-z0-9_-]+[[:space:]]*:/ {
      line = $0
      sub(/^[[:space:]]*/, "", line)

      name = line
      sub(/:.*/, "", name)

      value = line
      sub(/^[^:]*:[[:space:]]*/, "", value)

      sub(/[[:space:]]*;[[:space:]]*$/, "", value)

      printf "  --color-%s: var(%s);\n", substr(name, 8), name
    }
  ' "$colors"

  awk '
    /^[[:space:]]*--cros_[A-Za-z0-9_-]+[[:space:]]*:/ {
      line = $0
      sub(/^[[:space:]]*/, "", line)

      name = line
      sub(/:.*/, "", name)

      if (name ~ /_font_family$/) {
        printf "  --font-%s: var(%s);\n", substr(name, 8), name
      }
    }
  ' "$typography"

  printf '%s\n' '}'
} > "$output"

printf 'generated %s\n' "$output"
